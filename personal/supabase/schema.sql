-- Run in Supabase SQL Editor. Uses Supabase Auth UUIDs and row-level security.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '', currency char(3) not null default 'USD',
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  name varchar(80) not null, type varchar(8) not null check(type in ('INCOME','EXPENSE')),
  icon varchar(40) not null default 'circle', color char(7) not null default '#3478F6',
  created_at timestamptz not null default now()
);
create unique index if not exists categories_owner_name_type on public.categories(coalesce(user_id,'00000000-0000-0000-0000-000000000000'::uuid),lower(name),type);
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null references public.categories(id),
  transaction_type varchar(8) not null check(transaction_type in ('INCOME','EXPENSE')),
  amount numeric(19,2) not null check(amount>0), transaction_date date not null,
  source varchar(100), payment_method varchar(20), description varchar(500),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists transactions_owner_date on public.transactions(user_id,transaction_date desc);
create table if not exists public.budget_plans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  budget_month int not null check(budget_month between 1 and 12), budget_year int not null,
  total_budget numeric(19,2) not null check(total_budget>0),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(user_id,budget_year,budget_month)
);
create table if not exists public.budget_allocations (
  id bigint generated by default as identity primary key,
  budget_plan_id bigint not null references public.budget_plans(id) on delete cascade,
  category_id bigint not null references public.categories(id), planned_amount numeric(19,2) not null check(planned_amount>0),
  unique(budget_plan_id,category_id)
);
create table if not exists public.savings_goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name varchar(120) not null, target_amount numeric(19,2) not null check(target_amount>0), target_date date,
  description varchar(500), status varchar(10) not null default 'ACTIVE' check(status in ('ACTIVE','COMPLETED','ARCHIVED')),
  created_at timestamptz not null default now()
);
create table if not exists public.savings_contributions (
  id bigint generated by default as identity primary key,
  savings_goal_id bigint not null references public.savings_goals(id) on delete cascade,
  amount numeric(19,2) not null check(amount>0), contribution_date date not null, description varchar(500),
  created_at timestamptz not null default now()
);
create table if not exists public.interest_calculations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  calculation_type varchar(10) not null check(calculation_type in ('SIMPLE','COMPOUND')),
  principal numeric(19,2) not null, annual_rate numeric(9,4) not null, duration numeric(9,4) not null,
  duration_unit varchar(10) not null check(duration_unit in ('YEARS','MONTHS')), compounding_frequency varchar(15),
  interest_amount numeric(19,2) not null, final_amount numeric(19,2) not null, created_at timestamptz not null default now()
);

create or replace function public.create_profile_for_new_user() returns trigger language plpgsql security definer set search_path=public as $$
begin insert into public.profiles(id,full_name) values(new.id,coalesce(new.raw_user_meta_data->>'full_name','')); return new; end; $$;
drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users for each row execute procedure public.create_profile_for_new_user();

alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.transactions enable row level security;
alter table public.budget_plans enable row level security;
alter table public.budget_allocations enable row level security;
alter table public.savings_goals enable row level security;
alter table public.savings_contributions enable row level security;
alter table public.interest_calculations enable row level security;
create policy "profile owner access" on public.profiles for all using(id=auth.uid()) with check(id=auth.uid());
create policy "read shared or own categories" on public.categories for select using(user_id is null or user_id=auth.uid());
create policy "manage own categories" on public.categories for all using(user_id=auth.uid()) with check(user_id=auth.uid());
create policy "transaction owner access" on public.transactions for all using(user_id=auth.uid()) with check(user_id=auth.uid());
create policy "budget owner access" on public.budget_plans for all using(user_id=auth.uid()) with check(user_id=auth.uid());
create policy "allocation owner access" on public.budget_allocations for all using(exists(select 1 from public.budget_plans b where b.id=budget_plan_id and b.user_id=auth.uid())) with check(exists(select 1 from public.budget_plans b where b.id=budget_plan_id and b.user_id=auth.uid()));
create policy "goal owner access" on public.savings_goals for all using(user_id=auth.uid()) with check(user_id=auth.uid());
create policy "contribution owner access" on public.savings_contributions for all using(exists(select 1 from public.savings_goals g where g.id=savings_goal_id and g.user_id=auth.uid())) with check(exists(select 1 from public.savings_goals g where g.id=savings_goal_id and g.user_id=auth.uid()));
create policy "interest owner access" on public.interest_calculations for all using(user_id=auth.uid()) with check(user_id=auth.uid());

